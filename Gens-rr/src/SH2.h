struct __status_reg
{
	UINT8 T;
	UINT8 S;
	UINT8 IMask;
	UINT8 MQ;
};

typedef struct __status_reg STATREG;

struct __interrupt_struct
{
	UINT8 Vect;
	UINT8 Prio;
	UINT8 res1;
	UINT8 res2;
};

typedef struct __interrupt_struct INTSTR;


struct __fetch_region
{
	UINT32 Low_Adr;
	UINT32 High_Adr;
	UINT16 *Fetch_Reg;
};

typedef struct __fetch_region FETCHREG;


/* gens64: memory handlers are C functions (address, data, eax, context): eax is what the asm core had
   there (address >> 24, or the handler address in DMA transfers), the context the calling SH2.
   Reads return the value (byte/word in the low bits), writes return 0. */
struct __SH2_context;
typedef UINT32 SH2_HANDLER(UINT32 adr, UINT32 data, UINT32 eax, struct __SH2_context *ctx);
typedef SH2_HANDLER SH2_RB;
typedef SH2_HANDLER SH2_RW;
typedef SH2_HANDLER SH2_RL;
typedef SH2_HANDLER SH2_WB;
typedef SH2_HANDLER SH2_WW;
typedef SH2_HANDLER SH2_WL;

/* gens64: instruction handlers (SH2a_asm.c), given the core state; return the next step */
struct sh2_st;
typedef int SH2_INST(struct sh2_st *s);


