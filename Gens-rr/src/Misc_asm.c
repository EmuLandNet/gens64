/* gens64: C port of Misc.asm (r341): OSD text, blur, VRAM tile dumps, byte swaps, CDD status export,
 * sound output conversion, CPU detection.
 *
 * Only CDD_Export_Status (Sega CD state) and Byte_Swap (ROM loading) feed the emulation; the rest draws
 * into MD_Screen/MD_Screen32 or converts sound for output. Everything is kept bit-exact with the asm,
 * quirks included (checked with tools/test/misc_diff.sh against the original object):
 *  - the .data block (font, OSD palettes, masks) is copied verbatim from the asm object, and Print_Text
 *    still stores its blend mask into it; glyphs past the 97 in the font read the following bytes;
 *  - Print_Text truncates/terminates the caller's string in place;
 *  - 32-bit transparent x2 text reads the 4th pixel of each 2x2 block from half a row further down
 *    (offset 336*2 bytes instead of 336*4);
 *  - Half_Blur's MMX path averages each pixel with the next one, its non-MMX path with the previous one
 *    (and a different rounding);
 *  - the mono/stereo sound writers clamp an odd first sample differently from the MMX pairs.
 * The MMX code is written as plain C with the same saturation.
 */
