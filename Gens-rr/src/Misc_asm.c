void Identify_CPU(void)
{
	unsigned int a, b, c, d;

	Have_MMX = 0;
	CPU_Model = 0;
	if (__get_cpuid_max(0, 0) == 0)
		return;
	__cpuid(1, a, b, c, d);
	CPU_Model = (int)((a & 0xF00) | (d & 0xFFFFF0FF));
	*(u8 *)&Have_MMX = (CPU_Model & 0x00800000) != 0;
}

int Half_Blur(void)
{
	u16 *p = MD_Screen;
	int i;

	if (Have_MMX & 0xFF)
	{
		u16 rb = (Mode_555 & 1) ? 0x7C1F : 0xF81F;
		u16 g = (Mode_555 & 1) ? 0x03E0 : 0x07C0;
		for (i = 0; i < 336 * 240; i += 4)
		{
			u16 src[5];
			int k;
			for (k = 0; k < 5; k++)
				src[k] = p[i + k];
			for (k = 0; k < 4; k++)
			{
				u32 x = (u32)((src[k] & rb) >> 1) + ((src[k + 1] & rb) >> 1);
				u32 y = (u32)((src[k] & g) >> 1) + ((src[k + 1] & g) >> 1);
				if (x > 0xFFFF) x = 0xFFFF;	/* paddusw */
				if (y > 0xFFFF) y = 0xFFFF;
				p[i + k] = (u16)((x & rb) + (y & g));
			}
		}
	}
	else
	{
		u16 m1 = (Mode_555 & 1) ? 0x3C0F : 0x780F;
		u16 m2 = (Mode_555 & 1) ? 0x01E0 : 0x03E0;
		u16 di = 0, dx = 0;
		for (i = 0; i < 336 * 240; i++)
		{
			u16 ax = (u16)(p[i] >> 1);
			u16 bx = ax & m2;
			ax &= m1;
			di = (u16)(di + ax);
			dx = (u16)(dx + bx);
			dx = (u16)(dx + di);
			p[i] = dx;
			di = ax;
			dx = bx;
		}
	}
	return 0;
}

void Byte_Swap(void *Ptr, int NumByte)
{
	u16 *p = (u16 *)Ptr;
	u32 n = (u32)NumByte >> 1;
	while (n--)
	{
		*p = (u16)((*p << 8) | (*p >> 8));
		p++;
	}
}

void Word_Swap(void *Ptr, int NumByte)
{
	u32 *p = (u32 *)Ptr;
	u32 n = (u32)NumByte >> 2;
	while (n--)
	{
		*p = (*p << 16) | (*p >> 16);
		p++;
	}
}

