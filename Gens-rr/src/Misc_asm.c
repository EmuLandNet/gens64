static void letter16(u8 *d, const u8 *f, const u8 *pal, int mode, u16 m)
{
	int r, c;
	for (r = 0; r < 7; r++)
		for (c = 0; c < 4; c++)
		{
			u8 b = f[r * 4 + c];
			u16 a, x;
			u8 *q;
			if (!b)
				continue;
			a = rd16(pal + b * 2);
			switch (mode)
			{
			case 0:
				wr16(d + 336 * 2 * r + c * 2, a);
				break;
			case 1:
				q = d + 336 * 2 * r + c * 2;
				wr16(q, (u16)(((a & m) >> 1) + ((rd16(q) & m) >> 1)));
				break;
			case 2:
				q = d + 336 * 4 * r + c * 4;
				wr32(q, ((u32)a << 16) | a);
				wr32(q + 336 * 2, ((u32)a << 16) | a);
				break;
			default:
				q = d + 336 * 4 * r + c * 4;
				a = (u16)((a & m) >> 1);
				x = (u16)(((rd16(q) & m) >> 1) + a); wr16(q, x);
				x = (u16)(((rd16(q + 2) & m) >> 1) + a); wr16(q + 2, x);
				x = (u16)(((rd16(q + 336 * 2) & m) >> 1) + a); wr16(q + 336 * 2, x);
				x = (u16)(((rd16(q + 336 * 2 + 2) & m) >> 1) + a); wr16(q + 336 * 2 + 2, x);
				break;
			}
		}
}

static void letter32(u8 *d, const u8 *f, const u8 *pal, int mode, u32 m)
{
	int r, c;
	for (r = 0; r < 7; r++)
		for (c = 0; c < 4; c++)
		{
			u8 b = f[r * 4 + c];
			u32 a;
			u8 *q;
			if (!b)
				continue;
			a = rd32(pal + b * 4);
			switch (mode)
			{
			case 0:
				wr32(d + 336 * 4 * r + c * 4, a);
				break;
			case 1:
				q = d + 336 * 4 * r + c * 4;
				wr32(q, ((a & m) >> 1) + ((rd32(q) & m) >> 1));
				break;
			case 2:
				q = d + 336 * 8 * r + c * 8;
				wr32(q, a);
				wr32(q + 4, a);
				wr32(q + 336 * 4, a);
				wr32(q + 336 * 4 + 4, a);
				break;
			default:
				q = d + 336 * 8 * r + c * 8;
				a = (a & m) >> 1;
				wr32(q, ((rd32(q) & m) >> 1) + a);
				wr32(q + 4, ((rd32(q + 4) & m) >> 1) + a);
				wr32(q + 336 * 4, ((rd32(q + 336 * 4) & m) >> 1) + a);
				wr32(q + 336 * 4 + 4, ((rd32(q + 336 * 2 + 4) & m) >> 1) + a);	/* asm quirk */
				break;
			}
		}
}

void Print_Text(char *str, int Size, int Pos_X, int Pos_Y, int Style)
{
	static const unsigned short pal16[8] =
		{ PAL_BLANC_16, PAL_BLEU_16, PAL_VERT_16, PAL_ROUGE_16,
		  PAL_BLANC_15, PAL_BLEU_15, PAL_VERT_15, PAL_ROUGE_15 };
	static const unsigned short pal32[4] = { PAL_BLANC_32, PAL_BLEU_32, PAL_VERT_32, PAL_ROUGE_32 };
	u32 style = (u32)Style, size = (u32)Size, width = 320, end, sel;
	int bits32 = Bits32 & 1, mode;
	u8 *d;
	const u8 *pal;

	if (bits32)
		d = (u8 *)MD_Screen32 + 8 * 4 + (u32)Pos_X * 4 + (u32)Pos_Y * (336 * 4);
	else
		d = (u8 *)MD_Screen + 8 * 2 + (u32)Pos_X * 2 + (u32)Pos_Y * (336 * 2);

	if ((style & 1) && !(VDP_Reg[12 * 4] & 1))
		width = 256;
	end = (u32)Pos_X + size * 4;
	if (style & 0x10)
		end += size * 4;
	if (end >= width)
	{
		end = (end - width) >> 2;
		if (style & 0x10)
			end >>= 1;
		size -= end + 1;
		str[(int)size - 2] = '.';
		str[(int)size - 1] = '.';
	}
	str[(int)size] = 0;

	sel = (style >> 1) & 3;
	if (bits32)
	{
		wr32(gens64_misc_data + MASK_OFF, 0xFEFEFEFE);
		pal = gens64_misc_data + pal32[sel];
	}
	else if (Mode_555 & 1)
	{
		wr32(gens64_misc_data + MASK_OFF, 0x7BDE);
		pal = gens64_misc_data + pal16[sel | 4];
	}
	else
	{
		wr32(gens64_misc_data + MASK_OFF, 0xF7DE);
		pal = gens64_misc_data + pal16[sel];
	}
	if (!*str)
		return;
	pal += 12;
	mode = (int)((style & 0x18) >> 3);

	do
	{
		int c = (u8)*str - 32;
		const u8 *f = FONT + (c < 0 ? 0 : c) * 28;
		if (bits32)
		{
			letter32(d, f, pal, mode, rd32(gens64_misc_data + MASK_OFF));
			d += (mode & 2) ? 8 * 4 : 4 * 4;
		}
		else
		{
			letter16(d, f, pal, mode, rd16(gens64_misc_data + MASK_OFF));
			d += (mode & 2) ? 8 * 2 : 4 * 2;
		}
		str++;
	} while (*str);
}

/* ---- VRAM tile dumps for the debugger ---- */

static const int nib_shift[8] = { 12, 8, 4, 0, 28, 24, 20, 16 };

/* one 8-pixel row from a pattern dword; d points at the destination row */
static void pattern_row(u8 *d, u32 w, u32 pal_off, int bits32)
{
	int k;
	for (k = 0; k < 8; k++)
	{
		u32 n = (w >> nib_shift[k]) & 0xF;
		if (bits32)
			wr32(d + k * 4, n ? *(const u32 *)((const u8 *)MD_Palette32 + n * 4 + pal_off) : MD_Palette32[0]);
		else
			wr16(d + k * 2, n ? *(const u16 *)((const u8 *)MD_Palette + n * 2 + pal_off) : MD_Palette[0]);
	}
}

/* rows: patterns per screen row; lines: lines per pattern; skip: source bytes skipped after each pattern */
static void cell_dump(const u8 *src, int Palette, int rows, int lines, int pairs)
{
	int bits32 = Bits32 & 1, px = bits32 ? 4 : 2;
	u32 pal_off = (u32)Palette << (bits32 ? 6 : 5);
	u8 *d = bits32 ? (u8 *)MD_Screen32 + 13560 : (u8 *)MD_Screen + 6780;
	int row, half, pat, line;

	for (row = 0; row < rows; row++)
		for (half = 0; half < (pairs ? 2 : 1); half++)
		{
			for (pat = 0; pat < 16; pat++)
			{
				for (line = 0; line < lines; line++)
				{
					pattern_row(d, *(const u32 *)src, pal_off, bits32);
					src += 4;
					d += 336 * px;
				}
				d -= (336 * lines - 8) * px;
				if (pairs)
					src += 0x20;
			}
			d += (336 * lines - 8 * 16) * px;
			if (pairs)
				src -= half ? 0x20 : 0x400 - 0x20;
		}
}

void Cell_8x8_Dump(unsigned char *Adr, int Palette)
{
	cell_dump(Adr, Palette, 24, 8, 0);
}

void Cell_16x16_Dump(unsigned char *Adr, int Palette)
{
	cell_dump(Adr, Palette, 12, 8, 1);
}

void Cell_32x32_Dump(unsigned char *Adr, int Palette)
{
	cell_dump(Adr, Palette, 6, 32, 0);
}

/* ---- Sega CD drive status ---- */

void CDD_Export_Status(void)
{
	u16 s = (u16)CDD.Status, m = (u16)CDD.Minute, se = (u16)CDD.Seconde, f = (u16)CDD.Frame;
	u8 ext = (u8)CDD.Ext, sum;

	wr16(CDD.Rcv_Status + 0, s);
	wr16(CDD.Rcv_Status + 2, m);
	wr16(CDD.Rcv_Status + 4, se);
	*(u8 *)&CDD.Control &= 0x3;
	sum = (u8)(s + (s >> 8) + m + (m >> 8) + se + (se >> 8) + f + (f >> 8) + ext);
	wr16(CDD.Rcv_Status + 6, f);
	wr16(CDD.Rcv_Status + 8, (u16)((ext << 8) | (~sum & 0x0F)));
}

/* ---- sound output ---- */

static short sat16(int v)
{
	return (short)(v > 32767 ? 32767 : v < -32768 ? -32768 : v);
}

void Write_Sound_Mono_MMX(int *Left, int *Right, short *Dest, int length)
{
	u32 n = (u32)length >> 1;

	if (length & 1)
	{
		int s = Left[0];
		Left[0] = 0;
		s = (int)((u32)s + (u32)Right[0]);
		Right[0] = 0;
		if (s > 0xFFFF)
			Dest[0] = 0x7FFF;
		else if (s < -0xFFFF)
			Dest[0] = -0x7FFF;
		else
			Dest[0] = (short)((u32)s >> 1);
		Left++;
		Right++;
		Dest++;
	}
	while (n--)
	{
		short l0 = sat16(Left[0]), l1 = sat16(Left[1]), r0, r1;
		Left[0] = Left[1] = 0;
		r0 = sat16(Right[0]);
		r1 = sat16(Right[1]);
		Right[0] = Right[1] = 0;
		Dest[0] = (short)((l0 >> 1) + (r0 >> 1));
		Dest[1] = (short)((l1 >> 1) + (r1 >> 1));
		Left += 2;
		Right += 2;
		Dest += 2;
	}
}

static short clamp7fff(int v)
{
	return (short)(v > 0x7FFF ? 0x7FFF : v < -0x7FFF ? -0x7FFF : v);
}

void Write_Sound_Stereo_MMX(int *Left, int *Right, short *Dest, int length)
{
	u32 n = (u32)length >> 1;

	if (length & 1)
	{
		int l = Left[0], r;
		Left[0] = 0;
		Dest[0] = clamp7fff(l);
		r = Right[0];
		Right[0] = 0;
		Dest[1] = clamp7fff(r);
		Left++;
		Right++;
		Dest += 2;
	}
	while (n--)
	{
		int r0 = Right[0], r1 = Right[1], l0, l1;
		Right[0] = Right[1] = 0;
		l0 = Left[0];
		l1 = Left[1];
		Left[0] = Left[1] = 0;
		Dest[0] = sat16(l0);
		Dest[1] = sat16(r0);
		Dest[2] = sat16(l1);
		Dest[3] = sat16(r1);
		Left += 2;
		Right += 2;
		Dest += 4;
	}
}
